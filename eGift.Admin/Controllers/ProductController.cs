    #region Private Methods

    private async Task LoadDropdowns(ProductViewModel model)
    {
        var categories = await _webClient
            .GetAsync<List<CategoryViewModel>>(
                "/api/category");

        model.Categories = new SelectList(
            categories ?? new List<CategoryViewModel>(),
            "Id",
            "CategoryName",
            model.CategoryId);


        // Load sub categories for Edit / validation failure
        if (model.CategoryId > 0)
        {
            var subCategories = await _webClient
                .GetAsync<List<SubCategoryViewModel>>(
                    "/api/subcategory");

            var filteredSubCategories = (subCategories ?? [])
                .Where(x => x.CategoryId == model.CategoryId)
                .ToList();

            model.SubCategories = new SelectList(
                filteredSubCategories,
                "Id",
                "SubCategoryName",
                model.SubCategoryId);
        }
        else
        {
            model.SubCategories = new SelectList(
                Enumerable.Empty<SubCategoryViewModel>());
        }


        // Size enum
        var sizes = Enum
            .GetValues<Size>()
            .Select(size => new
            {
                Id = (int)size,
                Name = size.ToString()
            })
            .ToList();

        model.Sizes = new SelectList(
            sizes,
            "Id",
            "Name",
            model.SizeId);
    }

