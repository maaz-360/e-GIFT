    // POST: Product/Create
    [HttpPost]
    [ValidateAntiForgeryToken]
    public async Task<IActionResult> Create(ProductViewModel model)
    {
        try
        {
            // These are optional on Create because they are generated by the API
            ModelState.Remove(nameof(model.ProductImagePath));
            ModelState.Remove(nameof(model.PicturePath1));
            ModelState.Remove(nameof(model.PicturePath2));
            ModelState.Remove(nameof(model.PicturePath3));
            ModelState.Remove(nameof(model.PicturePath4));

            if (!ModelState.IsValid)
            {
                await LoadDropdowns(model);

                return View(model);
            }

            model.CreatedBy =
                Convert.ToInt32(
                    HttpContext.Session.GetInt32("UserId"));

            model.CreatedDate = DateTime.Now;

            using var formData = new MultipartFormDataContent();

            formData.Add(
                new StringContent(model.Name),
                nameof(model.Name));

            formData.Add(
                new StringContent(model.CategoryId.ToString()),
                nameof(model.CategoryId));

            formData.Add(
                new StringContent(model.SubCategoryId.ToString()),
                nameof(model.SubCategoryId));

            formData.Add(
                new StringContent(model.QuantityPerUnit.ToString()),
                nameof(model.QuantityPerUnit));

            formData.Add(
                new StringContent(model.UnitPrice.ToString()),
                nameof(model.UnitPrice));

            if (model.SizeId.HasValue)
            {
                formData.Add(
                    new StringContent(model.SizeId.Value.ToString()),
                    nameof(model.SizeId));
            }

            if (model.Discount.HasValue)
            {
                formData.Add(
                    new StringContent(model.Discount.Value.ToString()),
                    nameof(model.Discount));
            }

            formData.Add(
                new StringContent(model.UnitInStock.ToString()),
                nameof(model.UnitInStock));

            formData.Add(
                new StringContent(model.UnitInOrder.ToString()),
                nameof(model.UnitInOrder));

            formData.Add(
                new StringContent(model.ProductAvailable.ToString()),
                nameof(model.ProductAvailable));

            if (!string.IsNullOrWhiteSpace(model.ShortDescription))
            {
                formData.Add(
                    new StringContent(model.ShortDescription),
                    nameof(model.ShortDescription));
            }

            if (!string.IsNullOrWhiteSpace(model.LongDescription))
            {
                formData.Add(
                    new StringContent(model.LongDescription),
                    nameof(model.LongDescription));
            }

            formData.Add(
                new StringContent(model.IsDeleted.ToString()),
                nameof(model.IsDeleted));

            formData.Add(
                new StringContent(model.CreatedBy.ToString()),
                nameof(model.CreatedBy));

            formData.Add(
                new StringContent(model.CreatedDate.ToDateTimeString()),
                nameof(model.CreatedDate));

            // Main Product Image
            if (model.ProductImage != null &&
                model.ProductImage.Length > 0)
            {
                var imageContent =
                    new StreamContent(
                        model.ProductImage.OpenReadStream());

                imageContent.Headers.ContentType =
                    new System.Net.Http.Headers.MediaTypeHeaderValue(
                        model.ProductImage.ContentType);

                formData.Add(
                    imageContent,
                    nameof(model.ProductImage),
                    model.ProductImage.FileName);
            }

            // Picture 1
            if (model.Picture1 != null &&
                model.Picture1.Length > 0)
            {
                var imageContent =
                    new StreamContent(
                        model.Picture1.OpenReadStream());

                imageContent.Headers.ContentType =
                    new System.Net.Http.Headers.MediaTypeHeaderValue(
                        model.Picture1.ContentType);

                formData.Add(
                    imageContent,
                    nameof(model.Picture1),
                    model.Picture1.FileName);
            }

            // Picture 2
            if (model.Picture2 != null &&
                model.Picture2.Length > 0)
            {
                var imageContent =
                    new StreamContent(
                        model.Picture2.OpenReadStream());

                imageContent.Headers.ContentType =
                    new System.Net.Http.Headers.MediaTypeHeaderValue(
                        model.Picture2.ContentType);

                formData.Add(
                    imageContent,
                    nameof(model.Picture2),
                    model.Picture2.FileName);
            }

            // Picture 3
            if (model.Picture3 != null &&
                model.Picture3.Length > 0)
            {
                var imageContent =
                    new StreamContent(
                        model.Picture3.OpenReadStream());

                imageContent.Headers.ContentType =
                    new System.Net.Http.Headers.MediaTypeHeaderValue(
                        model.Picture3.ContentType);

                formData.Add(
                    imageContent,
                    nameof(model.Picture3),
                    model.Picture3.FileName);
            }

            // Picture 4
            if (model.Picture4 != null &&
                model.Picture4.Length > 0)
            {
                var imageContent =
                    new StreamContent(
                        model.Picture4.OpenReadStream());

                imageContent.Headers.ContentType =
                    new System.Net.Http.Headers.MediaTypeHeaderValue(
                        model.Picture4.ContentType);

                formData.Add(
                    imageContent,
                    nameof(model.Picture4),
                    model.Picture4.FileName);
            }

