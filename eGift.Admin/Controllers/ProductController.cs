    // GET: Product/GetSubCategories?categoryId=1
    [HttpGet]
    public async Task<IActionResult> GetSubCategories(int categoryId)
    {
        try
        {
            var subCategories = await _webClient
                .GetAsync<List<SubCategoryResponseViewModel>>(
                    "/api/subcategory");

            var filteredSubCategories = (subCategories ?? [])
                .Where(x => x.CategoryId == categoryId)
                .ToList();

            return Json(filteredSubCategories);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                "Exception in ProductController GetSubCategories/{categoryId}: {Message}",
                categoryId,
                ex.Message);

            return StatusCode(500);
        }
    }

