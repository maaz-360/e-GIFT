    // GET: Product
    [HttpGet]
    public async Task<IActionResult> Index()
    {
        try
        {
            var products = new ProductListViewModel();

            products.ProductList = await _webClient
                .GetAsync<List<ProductResponseViewModel>>(
                    "/api/product")
                ?? new List<ProductResponseViewModel>();

            return View(products);
        }
